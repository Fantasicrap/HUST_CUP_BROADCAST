  cells=t.rows[0].cells if rowdata is headers else t.add_row().cells
  for i,(c,text) in enumerate(zip(cells,rowdata)):
   c.width=Inches(widths[i]);c.vertical_alignment=WD_CELL_VERTICAL_ALIGNMENT.CENTER
   tcpr=c._tc.get_or_add_tcPr();m=OxmlElement('w:tcMar')
